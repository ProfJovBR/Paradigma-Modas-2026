import { test, expect } from '@playwright/test';
import { mockSupabase } from './mock-supabase';

test('theme errors, contrast validation, stale editor and missing migration', async ({ page, context }) => {
  const mock = await mockSupabase(context);
  await page.goto('http://127.0.0.1:5184/#aparencia');
  await page.getByLabel('E-mail').fill('admin@example.test');
  await page.getByLabel('Senha', { exact: true }).fill('test-only-password');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  const publish = page.getByRole('button', { name: 'Publicar tema', exact: true });
  await expect(publish).toBeEnabled();
  await page.getByLabel('Texto', { exact: true }).fill('#ffffff');
  await expect(publish).toBeDisabled();
  await expect(page.getByRole('alert')).toContainText('contraste');
  await page.getByRole('button', { name: 'Salvar rascunho', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Rascunho salvo');
  await page.reload();
  await expect(page.getByLabel('Texto', { exact: true })).toHaveValue('#ffffff');
  await page.getByLabel('Fundo da loja', { exact: true }).fill('#101010');
  await page.getByLabel('Superfícies', { exact: true }).fill('#202020');
  await expect(publish).toBeEnabled();
  mock.state.failTheme = true;
  await publish.click();
  await expect(page.getByRole('alert')).toContainText('Não foi possível confirmar');
  await expect(page.getByText('Tema publicado.', { exact: false })).toHaveCount(0);
  mock.state.failTheme = false;
  await publish.click();
  await expect(page.getByRole('status')).toContainText('Tema publicado');
  const store = await context.newPage();
  await store.goto('http://127.0.0.1:5183');
  await expect(store.locator('.store')).toHaveCSS('--background', '#101010');
  await expect(store.locator('.store')).toHaveCSS('color', 'rgb(255, 255, 255)');
  await expect(page.locator('.preview-frame')).toHaveCSS('color', 'rgb(255, 255, 255)');
  const other = await context.newPage();
  await other.goto('http://127.0.0.1:5184/#aparencia');
  await expect(other.getByRole('button', { name: 'Publicar tema' })).toBeEnabled();
  await page.getByLabel('Cor principal', { exact: true }).fill('#123456');
  await page.getByRole('button', { name: 'Salvar rascunho', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Rascunho salvo');
  await other.getByRole('button', { name: 'Publicar tema' }).click();
  await expect(other.getByRole('alert')).toContainText('outra aba');
  await other.getByRole('button', { name: 'Recarregar tema salvo' }).click();
  await expect(other.getByLabel('Cor principal', { exact: true })).toHaveValue('#123456');
  mock.state.failThemeLoad = true;
  await other.reload();
  await expect(other.getByRole('alert')).toContainText('migration');
  await expect(other.getByRole('button', { name: 'Publicar tema' })).toBeDisabled();
  mock.state.failThemeLoad = false;
  await other.getByRole('button', { name: 'Recarregar tema salvo' }).click();
  await expect(other.getByRole('button', { name: 'Publicar tema' })).toBeEnabled();
});
