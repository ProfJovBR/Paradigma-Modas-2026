import assert from 'node:assert/strict';

export async function testBanners({ db, role, denied, admin, ordinary }) {
  await db.exec('reset role');
  const bucket = (await db.query("select * from storage.buckets where id='banners'")).rows[0];
  assert.equal(bucket.public, false);
  assert.equal(Number(bucket.file_size_limit), 5000000);
  assert.deepEqual(bucket.allowed_mime_types, ['image/jpeg', 'image/png', 'image/webp']);
  const get = async slot => (await db.query('select * from public.site_banners where slot=$1', [slot])).rows[0];
  const prepare = async (slot = 'hero', ext = 'png') => (await db.query('select public.prepare_banner_upload($1,$2) as path', [slot, ext])).rows[0].path;
  const upload = async (path, mime = 'image/png', size = 100) => db.query("insert into storage.objects(bucket_id,name,metadata) values ('banners',$1,$2)", [path, JSON.stringify({ mimetype: mime, size })]);
  const publish = async (banner, path, alt = 'Banner de teste') => (await db.query('select public.publish_banner($1,$2,$3,$4) as value', [banner.slot, path, alt, banner.revision])).rows[0].value;
  const cleanup = async () => (await db.query('select public.claim_banner_cleanup() as path')).rows.map(r => r.path);
  for (const [name, user] of [['anon', ''], ['authenticated', ordinary]]) {
    await role(name, user);
    assert.equal((await db.query('select * from public.site_banners')).rows.length, 2);
    await denied("select public.prepare_banner_upload('hero','png')");
    await denied("select public.publish_banner('hero',null,'',gen_random_uuid())");
    await denied("select public.discard_banner_upload('hero/unknown.png')");
    await denied('select public.claim_banner_cleanup()');
    await denied("update public.site_banners set alt='forbidden'");
    await denied("insert into storage.objects(bucket_id,name) values ('banners','forbidden.png')");
    if (name === 'anon') await denied('select * from public.banner_assets');
    else assert.equal((await db.query('select * from public.banner_assets')).rows.length, 0);
  }
  await role('authenticated', admin);
  await denied("update public.site_banners set path=null");
  await denied("insert into public.banner_assets(path,slot) values ('forbidden','hero')");
  await assert.rejects(prepare('other'), e => e.code === '22023');
  await assert.rejects(prepare('hero', 'svg'), e => e.code === '22023');
  const initial = await get('hero');
  const first = await prepare();
  await assert.rejects(publish(initial, first), e => e.code === '22023');
  assert.equal((await get('hero')).path, null);
  await upload(first);
  await role('anon');
  assert.equal((await db.query("select * from storage.objects where bucket_id='banners'")).rows.length, 0);
  await role('authenticated', admin);
  let hero = await publish(initial, first);
  assert.equal(hero.path, first);
  await db.query('select public.discard_banner_upload($1)', [first]);
  assert.deepEqual(await cleanup(), []);
  assert.equal((await db.query("delete from storage.objects where bucket_id='banners' returning name")).rows.length, 0, 'Active images cannot be deleted');
  assert.equal((await db.query("update storage.objects set name=name where bucket_id='banners' returning name")).rows.length, 0, 'No overwrite');
  await role('anon');
  assert.equal((await db.query("select name from storage.objects where bucket_id='banners'")).rows[0].name, first);
  await role('authenticated', admin);
  hero = await publish(hero, first, 'Novo texto alternativo');
  assert.equal(hero.alt, 'Novo texto alternativo');
  const second = await prepare();
  await upload(second);
  await assert.rejects(publish(initial, second), e => e.code === '40001');
  await assert.rejects(publish(hero, second, 'x'.repeat(301)), e => e.code === '22023');
  const cta = await get('cta');
  await assert.rejects(publish(cta, second), e => e.code === '22023');
  hero = await publish(hero, second);
  assert.deepEqual(await cleanup(), [first]);
  await assert.rejects(publish(hero, first), e => e.code === '22023', 'Retired paths cannot be republished during cleanup');
  await role('anon');
  assert.deepEqual((await db.query("select name from storage.objects where bucket_id='banners'")).rows.map(r => r.name), [second]);
  await role('authenticated', admin);
  // Simulate Storage API removal in this SQL-only harness, never do this in hosted Supabase.
  assert.deepEqual((await db.query("delete from storage.objects where bucket_id='banners' returning name")).rows.map(r => r.name), [first]);
  hero = await publish(hero, null, '');
  assert.equal(hero.path, null);
  assert.deepEqual(await cleanup(), [second]);
  const invalid = await prepare('cta');
  await upload(invalid, 'image/svg+xml');
  await assert.rejects(publish(cta, invalid), e => e.code === '22023');
  const oversize = await prepare('cta');
  await upload(oversize, 'image/png', 5000001);
  await assert.rejects(publish(cta, oversize), e => e.code === '22023');
  const abandoned = await prepare();
  await upload(abandoned);
  await db.exec('reset role');
  await db.query("update public.banner_assets set created_at=now()-interval '25 hours' where path=$1", [abandoned]);
  await role('authenticated', admin);
  assert.ok((await cleanup()).includes(abandoned));
  await assert.rejects(publish(hero, abandoned), e => e.code === '22023');
  const discarded = await prepare();
  await upload(discarded);
  await db.query('select public.discard_banner_upload($1)', [discarded]);
  assert.ok((await cleanup()).includes(discarded));
  assert.equal((await get('cta')).path, null, 'Failures never publish invalid images');
}
