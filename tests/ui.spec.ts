    await page.getByRole('button', { name: 'Publicar produto', exact: true }).click();
    await expect(page.getByText('Produto publicado.', { exact: true })).toBeVisible();
    await store.reload();
    await expect(store.getByRole('heading', { name: 'Produto de teste isolado' })).toBeVisible();
    await store.getByRole('link').filter({has:store.getByRole('heading', {name:'Produto de teste isolado'})}).click();
    await expect(store.getByRole('heading', { name:'Produto de teste isolado' })).toBeVisible();
    await store.getByRole('combobox', {name:'Tamanho e cor'}).selectOption({index:1});
    await expect(store.getByText('Em estoque', {exact:true})).toBeVisible();
    await expect(store.getByRole('img', {name:'Foto de teste isolado'})).toBeVisible();
    expect(await store.getByRole('img', {name:'Foto de teste isolado'}).evaluate((el: HTMLImageElement) => el.naturalWidth)).toBeGreaterThan(0);
    await expect(store.getByText(/125,90/)).toBeVisible();
    expect(await store.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await store.screenshot({path:testInfo.outputPath('produto.png'),fullPage:true});
    await page.getByRole('button', { name:'Arquivar produto',exact:true }).click();
